package com.karthik.ledgerflow.repository;

/**
 * Package marker for the repository layer.
 *
 * All Spring Data JPA repositories should be placed in this package
 * and extend {@link org.springframework.data.jpa.repository.JpaRepository}
 * or one of its sub-interfaces.
 *
 * Example:
 * <pre>
 * {@code
 * @Repository
 * public interface AccountRepository extends JpaRepository<Account, Long> {
 *     List<Account> findByOwnerId(Long ownerId);
 * }
 * }
 * </pre>
 */
